#!/usr/bin/env python3
"""Generate Android and GPUI versions of the same editable RBX mark."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
brand = json.loads((ROOT / "brand/rbx-mark.json").read_text())
layers = brand["layers"]

def write(name, text):
    path = ROOT / name
    path.parent.mkdir(parents=True, exist_ok=True)
    if not path.exists() or path.read_text() != text:
        path.write_text(text)

def svg(fill, paths):
    body = "".join(
        f'<path fill="{fill}" fill-rule="evenodd" d="{path}"/>'
        for path in paths if path
    )
    return '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1536 1536">' + body + '</svg>\n'

asset = "upstream/rbx-native/assets/icons/brand/"
for layer in layers:
    for key in ("outline", "face"):
        if layer[key]:
            write(asset + f"rbx-mobile-{layer['name']}-{key}.svg", svg("#000000", [layer[key]]))

xml = [f'''<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp" android:height="108dp"
    android:viewportWidth="1536" android:viewportHeight="1536">
    <path android:fillColor="{brand["background"]}" android:pathData="M 0 0 L 1536 0 L 1536 1536 L 0 1536 Z" />
    <group android:pivotX="768" android:pivotY="768" android:scaleX="0.84" android:scaleY="0.84">''']
for layer in layers:
    for key, color in [("outline", brand["accent"]), ("face", brand["face"])]:
        if layer[key]:
            xml.append(f'        <path android:fillColor="{color}" android:fillType="evenOdd" android:pathData="{layer[key]}"/>')
xml.extend(["    </group>", "</vector>"])
write("android/res/drawable/rbx_mobile_icon.xml", "\n".join(xml) + "\n")
code = '''// Generated by scripts/generate_brand.py from brand/rbx-mark.json.
package com.rbxnative.androidport;

final class RbxGeometry {
'''
for key in ("accent", "face", "background"):
    code += f'    static final int {key.upper()} = 0xFF{brand[key][1:]};\n'
for key in ("outline", "face"):
    values = ",\n        ".join(json.dumps(layer[key]) for layer in layers)
    code += f'    static final String[] {key.upper()}_PATHS = {{\n        {values}\n    }};\n'
code += "    private RbxGeometry() {}\n}\n"
write("android/src/com/rbxnative/androidport/RbxGeometry.java", code)
